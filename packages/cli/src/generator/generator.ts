import { ProgramNode, RouteNode } from "../parser/ast.js";
import { routeModuleName } from "./routeModuleName.js";

export interface GeneratedFiles {
  authTypesCode: string;
  appRoutesCode: string;
}

export class CodeGenerator {
  constructor(
    private readonly ast: ProgramNode,
    private readonly modulesImportPath: string = "../modules",
  ) {}

  public generate(): GeneratedFiles {
    return {
      authTypesCode: this.generateAuthTypes(),
      appRoutesCode: this.generateAppRoutes(),
    };
  }

  private generateAuthTypes(): string {
    const roles = ["'PUBLIC'", ...this.ast.profiles.map((p) => JSON.stringify(p.name))];
    return `// Generated by @policyforges/cli. Recreate with 'policyforges compile'.
export type AppRole = ${roles.join(" | ")};
`;
  }

  private generateAppRoutes(): string {
    const publicRoutes = this.ast.routes.filter((route) => route.isPublic);
    const lazyImports = publicRoutes
      .map((route) => {
        const name = routeModuleName(route.path);
        return `const ${name} = lazy(() => import(${JSON.stringify(`${this.modulesImportPath}/${name}`)}));`;
      })
      .join("\n");
    const routeDeclarations = this.ast.routes
      .map((route) => this.buildRouteJSX(route))
      .join("\n");

    return `// Generated by @policyforges/cli. Recreate with 'policyforges compile'.
import React, { lazy, Suspense } from 'react';
import { BrowserRouter, Routes, Route } from 'react-router-dom';
import { DynamicProtectedRoute, AuthProvider } from '@policyforges/react';

${lazyImports}
const LoadingFallback = () => <div className="auth-loading">Loading...</div>;

export function AppRoutes() {
  return (
    <AuthProvider>
      <BrowserRouter>
        <Routes>
${routeDeclarations}
        </Routes>
      </BrowserRouter>
    </AuthProvider>
  );
}
`;
  }

  private buildRouteJSX(route: RouteNode): string {
    const routePath = JSON.stringify(route.path);
    if (route.isPublic) {
      const name = routeModuleName(route.path);
      return `          <Route path={${routePath}} element={
            <Suspense fallback={<LoadingFallback />}><${name} /></Suspense>
          } />`;
    }

    return `          <Route path={${routePath}} element={
            <DynamicProtectedRoute chunkName={${JSON.stringify(route.chunkName)}} />
          } />`;
  }
}
